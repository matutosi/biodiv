function addRowWithValues({ table, values }){
  // var table = document.getElementById('input_occ_a_tb'); var layer = 'H'; var species = 'new_species';
  // var table = document.getElementById('full_plot_tb'); var key = "item"; value = "new_val";
  addRow(table);
  const c_names = getColNames(table);
  const keys = Object.keys(values);
  const row_no   = table.rows.length - 1;
  for(const key of keys){
    const col_no = c_names.indexOf(key);
    if(col_no < 0) continue;
    const td = table.rows[row_no].cells[col_no];
    const value = (values[key] === void 0) ? '' : values[key];
  // console.log(c_names);
  // console.log(td);
  // console.log(values);
  // console.log(key);
    if(td.firstChild === null){                // fixed with no input
      td.innerHTML = value;
    }else{
      if(td.firstChild.value === void 0){      // fixed with input
        td.innerHTML = value;
      }else{
        if(td.firstChild.type === 'checkbox'){ // checkbox
          td.firstChild.checked = value;
        }else{
          td.firstChild.value = value;         // text/number/select input
        }
      }
    }
  }
}

